const vm = require('node:vm');
const fs = require('node:fs');
const assert = require('node:assert/strict');
let listener;
const context = vm.createContext({chrome:{runtime:{onMessageExternal:{addListener(fn){listener=fn}},onMessage:{addListener(){}}}},URL,console});
vm.runInContext(fs.readFileSync('extension/background.js','utf8'),context);
assert.equal(vm.runInContext("postUrl('7522886392381837312')",context),'https://www.linkedin.com/feed/update/urn:li:activity:7522886392381837312/');
assert.throws(()=>vm.runInContext("postUrl('https://evil.test')",context));
assert.equal(listener({type:'SAVESIFT_FETCH_POST',activityId:'7522886392381837312'},{url:'https://evil.test'},()=>{throw Error('Untrusted origin accepted')}),false);
let invalid;
listener({type:'SAVESIFT_FETCH_POST',activityId:'wrong'},{url:'https://save-sift.onrender.com/'},r=>{invalid=r});
assert.equal(invalid.status,'error');
context.location={pathname:'/login'};
assert.equal(vm.runInContext("extractPost('7522886392381837312').status",context),'login_required');
context.location={pathname:'/feed/update/urn:li:activity:7522886392381837312/',href:'https://www.linkedin.com/feed/update/urn:li:activity:7522886392381837312/'};
context.document={querySelector(){return null}};
assert.equal(vm.runInContext("extractPost('7522886392381837312').status",context),'not_ready');
const root={querySelector(sel){if(sel.includes('actor'))return {innerText:'Example Author'};return {innerText:'A post about inference.\nMore detail.'}}};
context.document={querySelector(){return root}};
const post=vm.runInContext("extractPost('7522886392381837312')",context);
assert.equal(post.status,'ok');assert.equal(post.title,'A post about inference.');assert.equal(post.author,'Example Author');
assert.equal(vm.runInContext("extractPost('7522886392381837313').status",context),'not_ready');
console.log('PASS: trusted origin checks, activity validation, login detection, missing content, extraction, and ID mismatch');
